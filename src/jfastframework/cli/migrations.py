migration_app = typer.Typer(
    help="Read migrations before they run: what fails, what locks, what is lost.",
    no_args_is_help=True,
)

_LEVELS = (*SEVERITY_ORDER, "never")

PathOption = Annotated[Path, typer.Option("--path", "-p", help="Project root.")]
DsnOption = Annotated[
    str | None,
    typer.Option("--dsn", help="Database to read row counts from. Defaults to JFAST_DB_DSN."),
]
NoDbOption = Annotated[
    bool, typer.Option("--no-db", help="Do not connect. Every table is treated as populated.")
]
JsonOption = Annotated[bool, typer.Option("--json", help="Machine-readable output.")]


def _gather(
    path: Path, dsn: str | None, no_db: bool, every: bool
) -> tuple[list[RevisionReport], str, str, str | None]:
    """`(reports, database, scope, error)` -- the whole of both commands' input."""
    root = path.resolve()
    if versions_dir(root) is None:
        typer.echo(f"no migrations/versions under {root}. Is this a service with a database?")
        raise typer.Exit(Code.CONFIG)

    revisions = load_revisions(root)
    resolved = None if no_db else resolve_dsn(root, dsn)

    rows = RowCounts.unknown()
    database = "skipped" if no_db else "unavailable"
    error: str | None = None
    head: str | None = None
    if resolved is not None:
        tables = sorted({table for revision in revisions for table in revision.tables()})
        head, rows, error = inspect_database(resolved, tables)
        database = "connected" if error is None else "unavailable"

    applied = applied_set(revisions, head)
    scope = "all"
    selected = revisions
    if not every and applied:
        selected = [revision for revision in revisions if revision.revision not in applied]
        scope = "unapplied"

    reports = [
        RevisionReport(revision=revision, risks=tuple(analyze_revision(revision, rows)))
        for revision in selected
    ]
    return reports, database, scope, error


@migration_app.command("check")
def check(
    path: PathOption = Path("."),
    every: Annotated[
        bool, typer.Option("--all", help="Check applied revisions too, not just pending ones.")
    ] = False,
    dsn: DsnOption = None,
    no_db: NoDbOption = False,
    json_out: JsonOption = False,
    fail_on: Annotated[
        str,
        typer.Option(
            "--fail-on",
            help="Exit non-zero at this severity or worse: critical, high, medium, low, never.",
        ),
    ] = "high",
) -> None:
    """What each unapplied revision will do to a database that has data in it.

    Reads `migrations/versions/*.py` with `ast` and never imports them, so it
    works on a project whose dependencies are not installed and on a revision
    that references a model that no longer exists.

    Row counts come from the database when a DSN resolves. When one does not,
    every table is reported as populated rather than assumed empty: a checker
    that goes quiet in the absence of evidence is quiet exactly where it was
    needed.
    """
    if fail_on not in _LEVELS:
        raise typer.BadParameter(f"choose from: {', '.join(_LEVELS)}", param_hint="--fail-on")

    reports, database, scope, error = _gather(path, dsn, no_db, every)
    risks = [risk for report in reports for risk in report.risks]

    payload = {
        "schema_version": SCHEMA_VERSION,
        "ok": not risks,
        "scope": scope,
        "database": database,
        "database_error": error,
        "counts": severity_counts(risks),
        "revisions": [report.describe() for report in reports],
    }
    if json_out:
        typer.echo(jsonlib.dumps(payload, indent=2, default=str))
    else:
        typer.echo(render_check(reports, database=database, scope=scope))

    if fail_on == "never":
        return
    threshold = SEVERITY_ORDER.index(fail_on)
    if any(SEVERITY_ORDER.index(risk.finding.severity) <= threshold for risk in risks):
        raise typer.Exit(Code.MIGRATION)


@migration_app.command("plan")
def plan(
    path: PathOption = Path("."),
    revision_id: Annotated[
        str | None, typer.Option("--revision", "-r", help="Plan this revision instead.")
    ] = None,
    dsn: DsnOption = None,
    no_db: NoDbOption = False,
    json_out: JsonOption = False,
) -> None:
    """The next risky revision, why it is risky, and the safe rewrite.

    Without `--revision` this is the first unapplied revision that carries a
    risk -- the one about to run and do something you did not ask for. The
    `Reason` line states a real row count when a database answered and says so
    when none did; it never reports a table as empty on no evidence.
    """
    reports, database, _, _ = _gather(path, dsn, no_db, every=False)

    if revision_id is not None:
        chosen = next((r for r in reports if r.revision.revision == revision_id), None)
        if chosen is None:
            typer.echo(f"no revision {revision_id!r} among the ones checked.")
            raise typer.Exit(Code.USAGE)
    else:
        chosen = next((report for report in reports if report.risks), None)
        if chosen is None:
            chosen = reports[0] if reports else None

    if chosen is None:
        typer.echo("no revisions to plan.")
        raise typer.Exit(Code.CONFIG)

    worst = chosen.risks[0] if chosen.risks else None
    if json_out:
        typer.echo(
            jsonlib.dumps(
                {
                    "schema_version": SCHEMA_VERSION,
                    "revision": chosen.revision.revision,
                    "path": chosen.revision.path,
                    "database": database,
                    "risk": worst.finding.severity if worst else None,
                    "reason": worst.reason if worst else None,
                    "finding": worst.finding.describe() if worst else None,
                    "steps": list(worst.steps) if worst else [],
                },
                indent=2,
                default=str,
            )
        )
    else:
        typer.echo(render_plan(chosen.revision, worst, database=database))

    if worst is not None and SEVERITY_ORDER.index(worst.finding.severity) <= SEVERITY_ORDER.index(
        "high"
    ):
        raise typer.Exit(Code.MIGRATION)


def register(app: typer.Typer) -> None:
    """Add the `migration` group to *app*. The whole public surface."""
    app.add_typer(migration_app, name="migration")
