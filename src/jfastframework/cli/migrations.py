def severity_counts(risks: Sequence[Risk]) -> dict[str, int]:
    counts = {severity: 0 for severity in SEVERITY_ORDER}
    for risk in risks:
        counts[risk.finding.severity] += 1
    return {severity: count for severity, count in counts.items() if count}


def render_check(reports: Sequence[RevisionReport], *, database: str, scope: str) -> str:
    """One block per revision, findings worst first, in `jfast analyze`'s shape."""
    G = ui.G
    if not reports:
        return f"  {G.tick} no {scope} revisions"

    lines: list[str] = []
    for report in reports:
        header = f"  {report.revision.revision}  {report.revision.path}"
        if not report.risks:
            lines.append(f"{header}  {G.tick}")
            continue
        lines.append(header)
        for risk in report.risks:
            finding = risk.finding
            where = f"line {finding.line}" if finding.line else ""
            lines.append(f"    {finding.severity.upper():<10}{finding.code}  {where}")
            lines.append(f"      {finding.message}")
            lines.append(f"      {finding.why}")
        lines.append("")

    all_risks = [risk for report in reports for risk in report.risks]
    counts = severity_counts(all_risks)
    if counts:
        lines.append("  " + "  ".join(f"{name} {count}" for name, count in counts.items()))
    else:
        lines.append(f"  {G.tick} nothing to report")
    lines.append(f"  database: {database}")
    if database != "connected":
        lines.append("  row counts unknown -- every table is treated as populated")
    return "\n".join(lines)


def render_plan(revision: Revision, risk: Risk | None, *, database: str) -> str:
    """The riskiest thing this revision does, and the safe way to do it."""
    G = ui.G
    if risk is None:
        return (
            f"Migration:  {revision.revision}\n"
            f"File:       {revision.path}\n"
            f"Risk:       none\n\n"
            f"  {G.tick} nothing in this revision needs rewriting"
        )
    lines = [
        f"Migration:  {revision.revision}",
        f"File:       {revision.path}",
        f"Risk:       {risk.finding.severity.upper()}",
        f"Reason:     {risk.reason}",
        f"Database:   {database}",
        "",
        f"  {risk.finding.code}: {risk.finding.message}",
        f"  {risk.finding.why}",
        "",
        "Recommended:",
    ]
    lines.extend(f"  {index}. {step}" for index, step in enumerate(risk.steps, start=1))
    return "\n".join(lines)


