"""`jfast migration check` and `jfast migration plan`.

A migration is the one edit that is applied exactly once, to the one copy of
the data that matters, usually by a deploy pipeline nobody is watching. The
failure modes are known and small in number -- it is rejected outright, it
holds a lock long enough to look like an outage, or it succeeds and the data is
wrong afterwards -- and every one of them is visible in the revision's source
before it runs. So this reads them.

**It never imports a revision.** A revision imports the project's models, and
the environment the CLI runs in is not the environment those imports resolve
in: a checker that only works when the project already imports is a checker
that is unavailable in the moment it is needed. Everything below comes out of
`ast`.

Relationship to the generated `migrations/env.py`: that file's
`process_revision_directives` hook repairs a scalar-default `NOT NULL` column
*at generation time*, so revisions autogenerated by a current service should
never trip `migration-add-not-null`. This command is the other half -- it reads
revisions that already exist, including hand-written ones, ones merged from a
branch, and ones generated before that hook existed. The two agree on what is
wrong; they disagree only about when there is still time to fix it.

Every check is decidable from the source text, and the ones that are not are
deliberately absent. A checker that is right nine times in ten is muted after
the second false positive, and the true findings go with it.

`op.execute` is the exception that proves it. Arbitrary SQL cannot be judged
without a SQL parser, so a named list of statement forms is read and everything
else is reported as **unread** rather than passed: `migration-raw-sql` at `low`.
A tick on a statement nobody looked at claims a review that did not happen, and
that is the failure this module exists to prevent.
"""

