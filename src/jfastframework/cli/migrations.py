@dataclass(frozen=True)
class Operation:
    """One `op.*` call, reduced to the parts a risk depends on."""

    name: str
    line: int
    table: str | None = None
    column: str | None = None
    #: The index or constraint the call names, which is not a column.
    target: str | None = None
    #: Keyword arguments as written. Values are source text, not objects: a
    #: type is `sa.Numeric(12, 2)` and there is nothing to evaluate it with.
    keywords: Mapping[str, str] = field(default_factory=dict)
    #: The type being moved *to*, from `type_=` or the column's own argument.
    type_text: str | None = None
    #: The literal handed to `op.execute`, when it was a literal.
    sql: str | None = None


@dataclass(frozen=True)
class Revision:
    """One file under `versions/`."""

    path: str
    revision: str
    down_revision: str | None
    message: str
    operations: tuple[Operation, ...]
    downgrade_is_empty: bool
    #: Where `downgrade` is declared, so a finding about it points at it.
    downgrade_line: int = 1

    def tables(self) -> frozenset[str]:
        return frozenset(op.table for op in self.operations if op.table)


@dataclass(frozen=True)
class RowCounts:
    """How full each table is, and whether that is actually known.

    `known=False` is not a synonym for empty and must never be treated as one.
    The whole point of the row count is the difference between "this will be
    rejected" and "this applied fine on the laptop it was written on".
    """

    known: bool
    counts: Mapping[str, int] = field(default_factory=dict)

    #: `counts[table]` when the server said there are rows but would only be
    #: exact after a table scan. Reported as "has rows".
    SOME = -1

    @classmethod
    def unknown(cls) -> RowCounts:
        return cls(known=False)

    def phrase(self, table: str) -> str:
        """How to finish the sentence "widgets ..."."""
        if not self.known:
            return "has an unknown row count, treat as populated"
        if table not in self.counts:
            return "does not exist on this database yet"
        count = self.counts[table]
        if count == 0:
            return "is empty on this database"
        if count == self.SOME:
            return "has rows"
        return "has 1 row" if count == 1 else f"has {count} rows"


@dataclass(frozen=True)
class Risk:
    """A finding, plus the two things `plan` needs that a finding does not carry.

    The finding is `jfastframework.project.Finding` unchanged: severity, code,
    message and why mean here exactly what they mean in `jfast analyze`, and
    render through the same code.
    """

    finding: Finding
    reason: str
    steps: tuple[str, ...]


@dataclass(frozen=True)
class RevisionReport:
    revision: Revision
    risks: tuple[Risk, ...]

    def describe(self) -> dict[str, Any]:
        return {
            "revision": self.revision.revision,
            "path": self.revision.path,
            "message": self.revision.message,
            "findings": [risk.finding.describe() for risk in self.risks],
            "reasons": [risk.reason for risk in self.risks],
        }


