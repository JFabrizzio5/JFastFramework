def _string(node: ast.expr | None) -> str | None:
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    # Autogenerate names every index and constraint `op.f("ix_widgets_slug")`,
    # which marks the name as already-final rather than changing it. The
    # argument is the literal, so reading through the wrapper is what makes a
    # generated revision name its own index instead of reporting `None`.
    if isinstance(node, ast.Call) and len(node.args) == 1:
        func = node.func
        if isinstance(func, ast.Attribute) and func.attr == "f":
            return _string(node.args[0])
    return None


def _sql_literal(node: ast.expr | None) -> str | None:
    """The SQL `op.execute` was handed, when the source says what it is.

    `op.execute(sa.text("..."))` is the form autogenerate and most hand-written
    data migrations use, so reading only the bare string leaves the common case
    unread. An f-string or a variable stays None: the statement does not exist
    yet, and there is nothing honest to say about it.
    """
    literal = _string(node)
    if literal is not None:
        return literal
    if isinstance(node, ast.Call) and len(node.args) == 1:
        func = node.func
        named = func.attr if isinstance(func, ast.Attribute) else getattr(func, "id", None)
        if named == "text":
            return _string(node.args[0])
    return None


def _positional(call: ast.Call, index: int) -> ast.expr | None:
    return call.args[index] if len(call.args) > index else None


def _keywords(call: ast.Call) -> dict[str, str]:
    return {kw.arg: ast.unparse(kw.value) for kw in call.keywords if kw.arg is not None}


def _keyword_string(call: ast.Call, name: str) -> str | None:
    """A keyword argument's *value*, not its source text.

    `_keywords` unparses, which is right for a type but wrong for a name:
    `table_name="widgets"` comes back as `'widgets'`, quote characters and all,
    and a table spelled that way matches nothing on the database.
    """
    for keyword in call.keywords:
        if keyword.arg == name:
            return _string(keyword.value)
    return None


def _attr_name(node: ast.expr) -> tuple[str, str] | None:
    """`(receiver, method)` for `receiver.method(...)`, else None."""
    if not isinstance(node, ast.Call) or not isinstance(node.func, ast.Attribute):
        return None
    if not isinstance(node.func.value, ast.Name):
        return None
    return node.func.value.id, node.func.attr


def _assigned(node: ast.stmt) -> tuple[list[ast.expr], ast.expr | None]:
    """`(targets, value)` for either assignment form, `([], None)` for anything else.

    `script.py.mako` writes `revision: str = "..."`, so the annotated form is
    the one this framework's own revisions arrive in; a parser that reads only
    `ast.Assign` reads none of them.
    """
    if isinstance(node, ast.Assign):
        return list(node.targets), node.value
    if isinstance(node, ast.AnnAssign):
        # `revision: str` with no value is legal and carries nothing.
        return [node.target], node.value
    return [], None


def _module_string(tree: ast.Module, name: str) -> str | None:
    """A top-level `name = "..."` assignment, which is how Alembic stamps ids."""
    for node in tree.body:
        targets, value = _assigned(node)
        if value is None:
            continue
        for target in targets:
            if isinstance(target, ast.Name) and target.id == name:
                literal = _string(value)
                if literal is not None:
                    return literal
                # A merge revision writes `down_revision = ("a", "b")`. The
                # first parent is enough to order the chain.
                if isinstance(value, ast.Tuple | ast.List) and value.elts:
                    return _string(value.elts[0])
    return None


def _function(tree: ast.Module, name: str) -> ast.FunctionDef | None:
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name == name:
            return node
    return None


def _is_empty(func: ast.FunctionDef | None) -> bool:
    """A body that is a docstring, `pass` or `...` and nothing else."""
    if func is None:
        return True
    for statement in func.body:
        if isinstance(statement, ast.Pass):
            continue
        if isinstance(statement, ast.Expr) and isinstance(statement.value, ast.Constant):
            continue
        return False
    return True


def _column_call(node: ast.expr | None) -> ast.Call | None:
    """The `sa.Column(...)` (or bare `Column(...)`) an `add_column` was handed."""
    if not isinstance(node, ast.Call):
        return None
    if isinstance(node.func, ast.Attribute) and node.func.attr == "Column":
        return node
    if isinstance(node.func, ast.Name) and node.func.id == "Column":
        return node
    return None


def _operation(call: ast.Call, batch_table: str | None) -> Operation | None:
    named = _attr_name(call)
    if named is None:
        return None
    _, method = named
    if method not in _OPERATIONS:
        return None

    line = call.lineno
    keywords = _keywords(call)

    if method == "execute":
        return Operation(name=method, line=line, sql=_sql_literal(_positional(call, 0)))

    if method in {"create_table", "drop_table"}:
        table = batch_table or _string(_positional(call, 0))
        return Operation(name=method, line=line, table=table, keywords=keywords)

    if method == "add_column":
        # Batch mode drops the table argument; it is on the `with` instead.
        column_node = _positional(call, 0 if batch_table else 1)
        table = batch_table or _string(_positional(call, 0))
        declared = _column_call(column_node)
        if declared is None:
            return Operation(name=method, line=line, table=table, keywords=keywords)
        # The column's own keywords are the ones that decide this: `nullable`
        # and `server_default` live on `sa.Column`, not on `op.add_column`.
        merged = {**keywords, **_keywords(declared)}
        return Operation(
            name=method,
            line=line,
            table=table,
            column=_string(_positional(declared, 0)),
            keywords=merged,
            type_text=(
                ast.unparse(declared.args[1]) if len(declared.args) > 1 else merged.get("type_")
            ),
        )

    if method == "drop_column":
        table = batch_table or _string(_positional(call, 0))
        column = _string(_positional(call, 0 if batch_table else 1))
        return Operation(name=method, line=line, table=table, column=column, keywords=keywords)

    if method == "alter_column":
        table = batch_table or _string(_positional(call, 0))
        column = _string(_positional(call, 0 if batch_table else 1))
        return Operation(
            name=method,
            line=line,
            table=table,
            column=column,
            keywords=keywords,
            type_text=keywords.get("type_"),
        )

    if method in {"create_index", "drop_index", "drop_constraint"}:
        target = _string(_positional(call, 0))
        table = batch_table or _string(_positional(call, 1)) or _keyword_string(call, "table_name")
        return Operation(name=method, line=line, table=table, target=target, keywords=keywords)

    return Operation(name=method, line=line, table=batch_table, keywords=keywords)


def _expressions(node: ast.stmt) -> Iterator[ast.expr]:
    """Expressions directly under *node*, skipping the bodies it may contain."""
    for child in ast.iter_child_nodes(node):
        if isinstance(child, ast.expr):
            yield child


def _scan(body: Sequence[ast.stmt], batch: tuple[str, str] | None, found: list[Operation]) -> None:
    """Collect operations, carrying the table a batch block binds.

    Written as a descent rather than `ast.walk` for one reason: inside
    `with op.batch_alter_table("widgets") as batch_op:` the operations no
    longer name their table, and a flat walk has nowhere to put that fact.
    """
    for node in body:
        if isinstance(node, ast.With | ast.AsyncWith):
            nested = batch
            for item in node.items:
                named = _attr_name(item.context_expr)
                if named is None or named[1] != "batch_alter_table":
                    continue
                assert isinstance(item.context_expr, ast.Call)
                table = _string(_positional(item.context_expr, 0))
                alias = item.optional_vars
                if table is not None and isinstance(alias, ast.Name):
                    nested = (alias.id, table)
            _scan(node.body, nested, found)
            continue

        for expression in _expressions(node):
            for sub in ast.walk(expression):
                if not isinstance(sub, ast.Call):
                    continue
                named = _attr_name(sub)
                if named is None:
                    continue
                receiver, _ = named
                if receiver == _ROOT_RECEIVER:
                    operation = _operation(sub, None)
                elif batch is not None and receiver == batch[0]:
                    operation = _operation(sub, batch[1])
                else:
                    continue
                if operation is not None:
                    found.append(operation)

        for attribute in ("body", "orelse", "finalbody"):
            nested_body = getattr(node, attribute, None)
            if isinstance(nested_body, list):
                _scan([n for n in nested_body if isinstance(n, ast.stmt)], batch, found)
        for handler in getattr(node, "handlers", []):
            _scan(handler.body, batch, found)


def parse_revision_source(source: str, *, path: str) -> Revision:
    """Read one revision from its text. Never imports it."""
    tree = ast.parse(source)
    upgrade = _function(tree, "upgrade")
    operations: list[Operation] = []
    if upgrade is not None:
        _scan(upgrade.body, None, operations)

    identifier = _module_string(tree, "revision") or Path(path).stem
    docstring = ast.get_docstring(tree) or ""
    downgrade = _function(tree, "downgrade")
    return Revision(
        path=path,
        revision=identifier,
        down_revision=_module_string(tree, "down_revision"),
        message=docstring.splitlines()[0].strip() if docstring else "",
        operations=tuple(operations),
        downgrade_is_empty=_is_empty(downgrade),
        downgrade_line=downgrade.lineno if downgrade is not None else 1,
    )


def parse_revision(path: Path, *, relative_to: Path | None = None) -> Revision | None:
    """Read one revision file, or None if it is not parseable Python."""
    try:
        source = path.read_text(encoding="utf-8")
    except OSError:
        return None
    display = path
    if relative_to is not None:
        with contextlib.suppress(ValueError):
            display = path.relative_to(relative_to)
    try:
        return parse_revision_source(source, path=display.as_posix())
    except SyntaxError:
        return None


def versions_dir(root: Path) -> Path | None:
    """Where the revisions are, honouring `script_location` in `alembic.ini`."""
    location = "migrations"
    ini = root / "alembic.ini"
    if ini.is_file():
        # Interpolation off: alembic.ini legitimately contains `%(here)s`, and
        # ConfigParser raises on it rather than leaving it alone.
        parser = configparser.ConfigParser(interpolation=None)
        try:
            parser.read(ini, encoding="utf-8")
        except (configparser.Error, OSError):
            pass
        else:
            location = parser.get("alembic", "script_location", fallback=location)
    candidate = root / location / "versions"
    return candidate if candidate.is_dir() else None


def order_revisions(revisions: list[Revision]) -> list[Revision]:
    """Dependency order. Filename order is a convention, not a guarantee."""
    known = {revision.revision for revision in revisions}
    children: dict[str | None, list[Revision]] = {}
    for revision in revisions:
        parent = revision.down_revision if revision.down_revision in known else None
        children.setdefault(parent, []).append(revision)

    ordered: list[Revision] = []
    seen: set[int] = set()

    def walk(parent: str | None) -> None:
        for revision in sorted(children.get(parent, []), key=lambda r: (r.revision, r.path)):
            if id(revision) in seen:
                continue
            seen.add(id(revision))
            ordered.append(revision)
            walk(revision.revision)

    walk(None)
    # A branch whose parent file is missing still has to be reported; dropping
    # it silently is how a checker ends up quieter than the tree it reads.
    for revision in revisions:
        if id(revision) not in seen:
            seen.add(id(revision))
            ordered.append(revision)
    return ordered


def load_revisions(root: Path) -> list[Revision]:
    """Every revision under the project's `versions/`, in dependency order."""
    directory = versions_dir(root)
    if directory is None:
        return []
    revisions = []
    for path in sorted(directory.glob("*.py")):
        if path.name == "__init__.py":
            continue
        revision = parse_revision(path, relative_to=root)
        if revision is not None:
            revisions.append(revision)
    return order_revisions(revisions)


