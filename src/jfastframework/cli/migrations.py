def resolve_dsn(root: Path, explicit: str | None) -> str | None:
    """The DSN to ask, or None. Never guesses one into existence.

    `DatabaseSettings` has a working default, which is the wrong behaviour
    here: it would turn "no database configured" into "connect to localhost",
    and a failed connection into a finding about the wrong database.
    """
    if explicit:
        return explicit
    from_env = os.environ.get("JFAST_DB_DSN")
    if from_env:
        return from_env
    # A workspace's .env is written for compose -- `<ws>-database:5432` and a
    # `${..._PASSWORD}` only compose fills in -- so read as is it names a host
    # nothing on this machine resolves, the connection fails, and the check
    # falls back to "every table populated" without saying the DSN was the
    # problem. Translated the way `jfast serve`, `worker` and `exec` do it;
    # inside a container, or with no compose file, nothing changes.
    from jfastframework.cli.dev import service_host_environment

    translated = service_host_environment(root).values.get("JFAST_DB_DSN")
    if translated:
        return translated
    dotenv = root / ".env"
    if dotenv.is_file():
        try:
            for raw in dotenv.read_text(encoding="utf-8").splitlines():
                line = raw.strip()
                if line.startswith("JFAST_DB_DSN") and "=" in line:
                    return line.split("=", 1)[1].strip().strip("\"'") or None
        except OSError:
            return None
    return None


async def _read_database(dsn: str, tables: Sequence[str]) -> tuple[str | None, dict[str, int]]:
    from sqlalchemy import text
    from sqlalchemy.engine import make_url
    from sqlalchemy.ext.asyncio import create_async_engine

    url = make_url(dsn)
    if url.get_backend_name() != "postgresql":
        raise RuntimeError(f"{url.get_backend_name()} is not PostgreSQL")
    url = url.set(drivername="postgresql+asyncpg")

    engine = create_async_engine(url, poolclass=None)
    try:
        async with engine.connect() as connection:
            head: str | None = None
            # Asked before it is read: on a database nothing has migrated yet
            # the SELECT fails, and a failed statement aborts the transaction
            # every query below runs in -- so a fresh database was reported as
            # "unavailable" rather than as empty and unmigrated.
            versioned = await connection.execute(
                text("SELECT to_regclass('alembic_version') IS NOT NULL")
            )
            if versioned.scalar():
                with contextlib.suppress(Exception):
                    result = await connection.execute(
                        text("SELECT version_num FROM alembic_version")
                    )
                    row = result.first()
                    head = str(row[0]) if row else None

            present = {
                str(name)
                for (name,) in (
                    await connection.execute(
                        text(
                            "SELECT c.relname FROM pg_class c "
                            "JOIN pg_namespace n ON n.oid = c.relnamespace "
                            "WHERE c.relkind = 'r' "
                            "AND n.nspname NOT IN ('pg_catalog', 'information_schema')"
                        )
                    )
                ).all()
            }
            estimates = {
                str(name): int(count)
                for name, count in (
                    await connection.execute(
                        text(
                            "SELECT c.relname, c.reltuples::bigint FROM pg_class c "
                            "JOIN pg_namespace n ON n.oid = c.relnamespace "
                            "WHERE c.relkind = 'r'"
                        )
                    )
                ).all()
            }

            counts: dict[str, int] = {}
            for table in tables:
                if table not in present:
                    continue
                try:
                    # An identifier cannot be bound as a parameter, so it is
                    # interpolated -- and therefore validated first, the same
                    # way the pgvector store and the PostgreSQL queue do it.
                    quoted = safe_identifier(table, kind="table")
                except ValueError:
                    # PostgreSQL accepts `"my table"` when quoted, and a
                    # read-only diagnostic has no business refusing to run over
                    # one. Unknown is already what this module reports with no
                    # database, and unknown is treated as populated.
                    counts[table] = RowCounts.SOME
                    continue
                # The estimate is stale by design and is -1 on a table that has
                # never been analysed. The EXISTS probe is what makes "empty"
                # mean empty, and it stops at the first row rather than
                # scanning a large table to say something already known.
                # The identifier is validated above; a *value* here would be
                # bound rather than interpolated. On its own line so the waiver
                # sits on the statement bandit reports, not on a continuation.
                probe_sql = f'SELECT EXISTS (SELECT 1 FROM "{quoted}" LIMIT 1)'  # nosec B608
                probe = await connection.execute(text(probe_sql))
                has_rows = bool(probe.scalar())
                estimate = estimates.get(table, 0)
                if not has_rows:
                    counts[table] = 0
                elif estimate > 0:
                    counts[table] = estimate
                else:
                    counts[table] = RowCounts.SOME
            return head, counts
    finally:
        await engine.dispose()


def inspect_database(dsn: str, tables: Sequence[str]) -> tuple[str | None, RowCounts, str | None]:
    """`(applied head, row counts, error)`. An error leaves the counts unknown."""
    try:
        head, counts = asyncio.run(_read_database(dsn, tables))
    except Exception as exc:  # noqa: BLE001 -- every failure means the same thing here
        return None, RowCounts.unknown(), f"{type(exc).__name__}: {exc}"
    return head, RowCounts(known=True, counts=counts), None


def applied_set(revisions: Sequence[Revision], head: str | None) -> frozenset[str]:
    """Every revision at or below *head*, walking the chain backwards."""
    if head is None:
        return frozenset()
    by_id = {revision.revision: revision for revision in revisions}
    applied: set[str] = set()
    cursor: str | None = head
    while cursor is not None and cursor not in applied:
        applied.add(cursor)
        current = by_id.get(cursor)
        cursor = current.down_revision if current else None
    return frozenset(applied)


